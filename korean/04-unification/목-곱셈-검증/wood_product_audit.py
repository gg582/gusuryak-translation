# 실행
# ---------------------------------------------------------------------------

def audit(g: dict) -> dict:
    N, C, cells = g["N"], g["C"], g["cells"]
    values = sorted({v for cell in cells.values() for v in cell})
    fire_nums = {v for v in values if ph(v) == FIRE}

    sigma = {r: (C - r) % 5 for r in range(5)}
    print(f"\n=== {g['name']}  (1..{N}, 보수합 C={C}, C mod 5={C % 5}) ===")
    print("  보수 대합 σ(r)=C−r:", ", ".join(f"{NAME[r]}↔{NAME[sigma[r]]}" for r in (1, 2, 3, 4, 0) if r <= sigma[r] or sigma[r] == 0 and r == 0))
    print(f"  木의 짝: {NAME[sigma[WOOD]]}{'  (목 자기보수)' if sigma[WOOD] == WOOD else ''}")

    stats = Counter()
    wood_pairs_in_cells = []
    cohab = []
    full_decomp = 0
    for key, cell in cells.items():
        pairs, rest = complement_pairs(cell, C)
        types = [pair_type(a, b) for a, b in pairs]
        stats.update(types)
        if len(rest) <= 1:
            full_decomp += 1
        prod5 = 1
        for v in cell:
            prod5 = prod5 * v % 5
        woods = [v for v in cell if ph(v) == WOOD]
        has_fire = any(ph(v) == FIRE for v in cell)
        if len(woods) >= 2:
            cohab.append((key, has_fire))
        wood_pairs_in_cells += list(combinations(woods, 2))
        print(f"  {key:>6}: {residue_profile(cell):<22} 보수쌍 {' '.join(types) or '-':<14}"
              f" 잔여 {rest or '-'}  ∏ mod5={NAME[prod5]}")

    print(f"  보수쌍 유형 집계: {dict(stats)}  / 완전 분해 궁 {full_decomp}/{len(cells)}")

    # C. 궁 내 목·목 곱
    hit5 = sum(1 for a, b in wood_pairs_in_cells if ph(a * b) == FIRE)
    hitN = sum(1 for a, b in wood_pairs_in_cells if (a * b) % N in fire_nums)
    hitC = sum(1 for a, b in wood_pairs_in_cells if (a * b) % C in fire_nums)
    base = len(fire_nums) / len(values)
    n = len(wood_pairs_in_cells)
    if n:
        print(f"  궁 내 木·木 쌍 {n}개: 곱 mod5=화 {hit5}/{n}, "
              f"(곱 mod N)∈화 {hitN}/{n}, (곱 mod C)∈화 {hitC}/{n}  [기저율 {base:.2f}]")
    else:
        print("  궁 내 木·木 쌍 없음")
    if cohab:
        print(f"  목 2개 이상 궁의 화 동거: {sum(f for _, f in cohab)}/{len(cohab)} "
              f"({', '.join(k + ('+화' if f else '') for k, f in cohab)})")
    return {"name": g["name"], "C5": C % 5, "stats": stats, "n": n,
            "hit5": hit5, "hitN": hitN, "hitC": hitC, "base": base,
            "wood_self": sigma[WOOD] == WOOD, "cohab": cohab,
            "full": full_decomp, "cells": len(cells)}


def main() -> None:
    print("mod 5 곱셈표 (행×열):")
    print(mul_table())
    print("\n목의 거듭제곱: " + ", ".join(f"木^{k}={NAME[pow(3, k, 5)]}" for k in range(1, 5)))
    print("보수쌍 곱 n·(C−n) mod 5 (C≡1): "
          + ", ".join(f"{HANJA[r]}{HANJA[(1 - r) % 5]}→{NAME[r * (1 - r) % 5]}" for r in (1, 2, 3)))

    results = [audit(g) for g in GRAPHS]

    print("\n\n=== 요약 ===")
    print(f"{'그래프':<28}{'C mod5':>7}{'木自補':>6}{'木木쌍':>7}{'mod5火':>7}{'modN火':>7}{'modC火':>7}  보수쌍 유형")
    for r in results:
        print(f"{r['name']:<28}{r['C5']:>7}{'O' if r['wood_self'] else '-':>6}{r['n']:>7}"
              f"{r['hit5']:>7}{r['hitN']:>7}{r['hitC']:>7}  {dict(r['stats'])}")
    tot = sum(r["n"] for r in results)
    print(f"\n전체 궁 내 木·木 쌍 {tot}개 중 곱이 화(mod 5)인 것: {sum(r['hit5'] for r in results)}")
    print(f"(곱 mod N)이 그 도형의 화 숫자: {sum(r['hitN'] for r in results)}, "
          f"(곱 mod C): {sum(r['hitC'] for r in results)}, "
          f"기대값(기저율 가중) ≈ {sum(r['n'] * r['base'] for r in results):.1f}")

    print("\n낙서육고도(1..270, C=271≡1): 목 자기보수 — 대척쌍 v+v'=271 의 유형은 "
          "水土·火金·木木 세 가지뿐 (도형 데이터 없이 성립).")


